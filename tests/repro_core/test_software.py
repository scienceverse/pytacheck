def _io(**scripts: dict[str, list[str]]) -> pd.DataFrame:
    """A ``repro_file_io()``-shaped table."""
    return pd.DataFrame(
        {
            "file_name": list(scripts),
            "reads": [s["reads"] for s in scripts.values()],
            "writes": [s["writes"] for s in scripts.values()],
            "sources": [s.get("sources", []) for s in scripts.values()],
        }
    )


def test_sw_chain_links_the_scripts_the_analysis_depends_on() -> None:
    # a figure notebook (linked) reads what the pipeline writes, with a pattern
    f = ["figures.ipynb", "train.py", "metrics.py", "tutorial.py", "driver.py"]
    k = [None, "unlinked", "unlinked", "unlinked", "unlinked"]
    links = ["names Figure 3", None, None, None, None]
    x = _io(
        **{
            "figures.ipynb": {"reads": ["rmse_per_hour.csv"], "writes": ["fig3.png"]},
            "train.py": {"reads": ["raw.csv"], "writes": ["model.pkl"]},
            "metrics.py": {"reads": ["model.pkl"], "writes": ["{metric}_per_hour.csv"]},
            "tutorial.py": {"reads": ["example.csv"], "writes": ["out.png"]},
            "driver.py": {"reads": [], "writes": []},
        }
    )
    ch = _repro_sw_chain(k, f, x, imported={"train.py": ["driver.py"]}, links=links)
    # the metrics script makes what the figure notebook reads, by a pattern
    assert ch[2] == "figures.ipynb needs what it makes"
    # the training script makes what the metrics script reads: along the chain
    assert ch[1] == "metrics.py needs what it makes"
    # a tutorial on example data stays unlinked
    assert ch[3] is None
    # a driver that imports a linked script runs that part of the analysis
    assert ch[4] == "it runs train.py"
    # a script that works on what the analysis makes
    x2 = _io(
        **{
            "a.R": {"reads": ["d.csv"], "writes": ["res.csv"]},
            "b.R": {"reads": ["res.csv"], "writes": []},
        }
    )
    assert _repro_sw_chain([None, "unlinked"], ["a.R", "b.R"], x2) == [
        None,
        "it works on what a.R makes",
    ]
    # source() counts, and nothing across repositories
    x3 = _io(
        **{
            "a.R": {"reads": [], "writes": [], "sources": ["helpers.r"]},
            "helpers.R": {"reads": [], "writes": []},
        }
    )
    assert (
        _repro_sw_chain([None, "unlinked"], ["a.R", "helpers.R"], x3)[1]
        == "a.R needs what it makes"
    )
    across = _repro_sw_chain([None, "unlinked"], ["a.R", "helpers.R"], x3, repos=["r1", "r2"])
    assert across[1] is None
    # nothing to do without unlinked scripts
    assert _repro_sw_chain([None, None], ["a.R", "b.R"], x2) == [None, None]
    # the links in words, for table$paper_link
    assert _repro_sw_link_text(["names_results, data", "a.R needs what it makes", None]) == [
        "it names the paper's figures or tables; it reads data deposited with the paper",
        "a.R needs what it makes",
        None,
    ]


