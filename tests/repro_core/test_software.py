def test_steps_2a_and_5c_r_package_code_and_tests_not_vignettes_or_paper() -> None:
    files = [
        "DESCRIPTION",
        "NAMESPACE",
        "R/model.R",
        "R/RcppExports.R",
        "src/model.cpp",
        "tools/make.R",
        "tests/testthat/test-model.R",
        "tests/testthat.R",
        "vignettes/intro.Rmd",
        "inst/examples/ex.R",
        "data-raw/make_data.R",
        "README.Rmd",
        "notes.R",
        "paper/figure1.R",
        "paper/sims/run.R",
    ]
    scripts = [f for f in files if f.endswith((".R", ".Rmd"))]
    out = sw_kind(scripts, files)
    k = dict(zip(scripts, kinds(out), strict=True))
    assert [k["R/model.R"], k["tools/make.R"]] == ["package", "package"]
    assert [k["tests/testthat/test-model.R"], k["tests/testthat.R"]] == ["test", "test"]
    unlinked = [
        "vignettes/intro.Rmd",
        "inst/examples/ex.R",
        "data-raw/make_data.R",
        "README.Rmd",
        "notes.R",
    ]
    assert all(k[f] == "unlinked" for f in unlinked)
    assert k["paper/figure1.R"] is None
    assert k["paper/sims/run.R"] is None
    i = scripts.index("R/model.R")
    assert col(out, "software")[i] == "repo"
    assert "part of the code of the package repo" in col(out, "why")[i]
    # an R/ folder alone is no package: authors keep their functions there too
    out = sw_kind(["R/functions.R", "analysis.R"], ["R/functions.R", "analysis.R", "README.md"])
    assert all(k is None for k in kinds(out))
    # an archive's listing can leave DESCRIPTION out: R/ next to man/*.Rd is a package
    files = ["pkg_0.1.tar.gz/pkg/R/a.R", "pkg_0.1.tar.gz/pkg/man/a.Rd", "analysis.R"]
    out = sw_kind(["pkg_0.1.tar.gz/pkg/R/a.R", "analysis.R"], files)
    assert kinds(out) == ["package", None]


