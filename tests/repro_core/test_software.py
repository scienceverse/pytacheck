    assert all(w is None for w in col(out, "why"))
    assert list(out.columns) == ["kind", "software", "why", "links"]
    empty = _repro_software_kind([], [])
    assert len(empty) == 0
    assert list(empty.columns) == ["kind", "software", "why", "links"]


