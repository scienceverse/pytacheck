def test_py_imported_finds_modules_not_scripts() -> None:
    code = {
        "main.py": [
            "import os",
            "from utils import helpers",
            "from modules.math_class import Math",
        ],
        "helpers.py": ["def f(): return 1"],
        "__init__.py": [],
        "math_class.py": ["class Math: pass"],
        "tool.py": ["def g(): pass", "if __name__ == '__main__':", "    g()"],
        "alone.py": ["print(1)"],
    }
    paths = [
        "code/main.py",
        "code/utils/helpers.py",
        "code/utils/__init__.py",
        "code/modules/math_class.py",
        "code/tool.py",
        "code/alone.py",
    ]
    imp = _repro_py_imported(code, paths)
    assert set(imp) == {"helpers.py", "__init__.py", "math_class.py"}
    assert imp["helpers.py"] == ["main.py"]
    # a file with a __main__ block, or that nothing imports, is a script
    code["main.py"] = [*code["main.py"], "import tool"]
    assert "tool.py" not in _repro_py_imported(code, paths)
    # a notebook cannot be imported: `import audio` names a module, not audio.ipynb (#568)
    nb = {
        "demo.ipynb": ["from opensoundscape import audio", "import audio"],
        "audio.ipynb": ["x = 1"],
    }
    assert _repro_py_imported(nb, ["docs/demo.ipynb", "docs/audio.ipynb"]) == {}


def test_py_imported_of_same_named_modules_only_the_one_the_importer_can_reach() -> None:
    code = {
        "a/m.py": ["import utils"],
        "a/utils.py": ["x = 1"],
        "b/utils.py": ["x = 2"],
        "c/n.py": ["from b.utils import x"],
        "d/utils.py": ["x = 3"],
    }
    imp = _repro_py_imported(code, list(code))
    assert set(imp) == {"a/utils.py", "b/utils.py"}
    assert imp["a/utils.py"] == ["a/m.py"]
    assert imp["b/utils.py"] == ["c/n.py"]


def test_a_packages_tests_and_setup_py_are_recognised_and_analyses_are_not() -> None:
    assert _repro_is_r_test("pkg/tests/testthat/test-a.R") is True
