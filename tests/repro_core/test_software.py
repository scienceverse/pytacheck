def test_a_root_belongs_to_its_repository() -> None:
    files = pd.concat(
        [
            sw_files(["DESCRIPTION", "NAMESPACE", "R/a.R"], "pkg"),
            sw_files(["R/model.R", "analysis.R"], "study"),
        ],
        ignore_index=True,
    )
    out = _repro_software_kind(
        ["R/a.R", "R/model.R", "analysis.R"], [["x"]] * 3, files, ["pkg", "study", "study"]
    )
    assert kinds(out) == ["package", None, None]
    # without the scripts' repositories, a root at the top of one repository cannot be
    # placed among several, so it is not used
    out = _repro_software_kind(["R/a.R", "R/model.R"], [["x"]] * 2, files, None)
    assert all(k is None for k in kinds(out))
    # with one repository it is
    out = _repro_software_kind(
        ["R/a.R"], [["x"]], sw_files(["DESCRIPTION", "NAMESPACE", "R/a.R"]), None
    )
    assert kinds(out) == ["package"]


