def test_step_6a_paper_names_script_specific_folder_or_appendix() -> None:
    paper = (
        "The simulations were run with run_sims_v2.R, and the long form of the analysis is "
        "in Appendix S2. A demo is included. The examples in BeeCaseStudy show the method."
    )
    scripts = [
        "examples/run_sims_v2.R",
        "vignettes/long_form.Rmd",
        "vignettes/other.Rmd",
        "examples/demo.R",
        "inst/BeeCaseStudy/fit.R",
        "inst/model/fit2.R",
    ]
    raw: list[Any] = [
        ["x <- 1"],
        ["---", "title: 'APPENDIX S2: analytical demonstrations'", "---"],
        ["---", "title: 'Appendix S3'", "---"],
        ["x <- 1"],
        ["x <- 1"],
        ["x <- 1"],
    ]
    out = sw_kind(scripts, SW_PKG + scripts, paper=paper, raw=raw)
    # "demo" and "model" are words, not names of this file or folder; S3 is not in the paper
    assert kinds(out) == [None, None, "unlinked", "unlinked", None, "unlinked"]
    assert "appendix" in col(out, "links")[1]
    assert (
        "documents or tests the software repo; nothing links it to the paper's results"
        in col(out, "why")[2]
    )
    # without the paper's text, this signal is absent
    out = sw_kind(scripts[:1], SW_PKG + scripts[:1])
    assert kinds(out) == ["unlinked"]
    # the paper links to the rendered vignette; "step-by-step" is also a phrase
    paper = (
        "The sources of Table 1 are in https://docs.ropensci.org/pkg/articles/data-sources.html."
    )
    scripts = ["vignettes/data-sources.Rmd", "vignettes/step-by-step.Rmd"]
    assert kinds(sw_kind(scripts, SW_PKG + scripts, paper=paper)) == [None, "unlinked"]
    out = sw_kind(scripts[1:], SW_PKG + scripts, paper="We give a step-by-step account.")
    assert kinds(out) == ["unlinked"]
    # a paper that points to its tutorials as documentation does not link them to its
    # results, nor does naming the software name its main vignette
    paper = (
        "See the main tutorial on the website https://x.github.io/gift/articles/gift_api.html "
        "for more details. The repo package provides ..."
    )
    scripts = ["vignettes/gift_api.Rmd", "vignettes/repo.Rmd"]
    assert kinds(sw_kind(scripts, SW_PKG + scripts, paper=paper)) == ["unlinked", "unlinked"]


