def _repro_software_place(
    path: str, repo: str | None, roots: Sequence[_Root], listed: _Listed
) -> _Place:
    """Port of R/reproducibility_check_software.R::.repro_software_place().

    Steps 3 to 5: where the file sits. Returns a :class:`_Place` (R's list ``kind``,
    ``software``, ``root_name``, ``paper_dir``, ``root``, ``root_repo``), ``root_name``
    being the name of the nearest root the file is in (``None`` when none).
    """
    if not roots:
        return _Place()
    repo = repo or ""
    # a root at the top of a repository applies to a file of that repository, or, when the
    # file's repository is not known, only in a deposit of one repository
    inside = [
        r
        for r in roots
        if (r.repo == repo or (not repo and (bool(r.root) or listed.one_repo)))
        and (not r.root or path.startswith(r.root + "/"))
    ]
    if not inside:
        return _Place()
    r = sorted(inside, key=lambda x: -len(x.root))  # the nearest root first
    near_name, root, root_repo = r[0].name, r[0].root, r[0].repo

    def out(
        kind: str | None = None,
        software: str | None = None,
        root_name: str | None = None,
        paper_dir: bool = False,
    ) -> _Place:
        return _Place(kind, software, root_name, paper_dir, root, root_repo)

    def parts_below(rt: str) -> list[str]:
        below = path[len(rt) + 1 :] if rt else path
        return below.split("/")[:-1]

    # 3. a web application or a copy of a tool, and any root inside one: the outermost
    # names the software
    wt = [x for x in r if x.type in ("web_app", "tool")]
    if wt:
        return out(wt[-1].type, wt[-1].name, near_name)
    # 4. the paper's analysis in a folder of its own (not one inside tests/: tests/analysis/
    # holds tests)
    outer = [p.lower() for p in parts_below(r[-1].root)]
    at_analysis = [k for k, p in enumerate(outer) if grepl(_SW_ANALYSIS_DIR, p)]
    at_test = [k for k, p in enumerate(outer) if grepl(_SW_TEST_DIR, p)]
    if at_analysis and (not at_test or at_analysis[0] < at_test[0]):
        return out(root_name=near_name, paper_dir=True)
    is_notebook = bool(grepl(r"\.(ipynb|rmd|qmd)$", path, ignore_case=True))
    # 5. seen from each root, the outermost first, which names the software (ESP-IDF rather
    # than one of its components)
    for j in range(len(r) - 1, -1, -1):
        rj = r[j]
        parts = parts_below(rj.root)
        folders = [p.lower() for p in parts]
        name = rj.name
        if any(grepl(_SW_TEST_DIR, f) for f in folders):
            return out("test", name, near_name)
        if rj.type == "compiled":
            # a compiled project inside another one is a part of it (a module of a 3D
            # Slicer extension, an example project of ESP-IDF)
            inner = any(x.type == "compiled" for x in r[:j])
            if any(grepl(_SW_CODE_DIR, f) for f in folders) or inner:
                return out("tool", name, near_name)
            continue
        if not folders:
            continue
        keep_at = [k for k, f in enumerate(folders) if grepl(_SW_KEEP_DIR, f)]
        if rj.type == "r_package":
            if not keep_at and folders[0] in ("r", "src", "tools", "exec"):
                return out("package", name, near_name)
            continue
        # a Python package's code: below a folder with __init__.py (also its scripts/
        # folder, cutadapt/scripts/), or in src/ or bin/; a notebook is never a module to
        # import, but a worked example
        if is_notebook:
            continue
        pkg_at = [
            k
            for k in range(len(parts))
            if (rj.repo, "/".join([*([rj.root] if rj.root else []), *parts[: k + 1]]))
            in listed.init_dirs
        ]
        if pkg_at and (not keep_at or pkg_at[0] < keep_at[0]):
            return out("package", name, near_name)
        if keep_at:
            continue
        if folders[0] in ("src", "bin"):
            return out("package", name, near_name)
        if folders[0] in ("docs", "doc"):
            return out("docs", name, near_name)
        if folders[0] == "ci":
            return out("ci", name, near_name)
    return out(root_name=near_name)


