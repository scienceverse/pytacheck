def _repro_software_roots(listed: _Listed) -> list[_Root]:
    """Port of R/reproducibility_check_software.R::.repro_software_roots().

    Step 2: the roots of software among the deposit's files, one per folder (the first of
    a tool, a web application, a package, compiled software): repository, root (the
    folder, ``""`` for the top of the repository), type (``tool``, ``web_app``,
    ``r_package``, ``py_package``, ``compiled``) and name. R returns a data frame of these
    columns; here it is a list of :class:`_Root` records.
    """
    if not listed.path:
        return []
    base, dir_ = listed.base, listed.dir
    key = list(zip(listed.repo, dir_, strict=True))

    def in_dir(names: Iterable[str]) -> list[tuple[str, str]]:
        wanted = set(names)
        return _unique(k for k, b in zip(key, base, strict=True) if b in wanted)

    def parent(ks: Iterable[tuple[str, str]]) -> list[tuple[str, str]]:
        return [(r, d.rpartition("/")[0]) for r, d in ks]

    def union(a: Iterable[Any], b: Iterable[Any]) -> list[Any]:
        return _unique([*a, *b])

    def intersect(a: Iterable[Any], b: Iterable[Any]) -> list[Any]:
        keep = set(b)
        return [x for x in _unique(a) if x in keep]

    # a. R package; help files (man/*.Rd) next to R/ only occur in a package, and a
    # listing of an archive can leave DESCRIPTION out
    r_dirs = parent(
        _unique(
            k
            for k, b, d in zip(key, base, dir_, strict=True)
            if b.endswith((".R", ".r")) and _basename(d) == "R"
        )
    )
    rd_dirs = parent(
        _unique(
            k
            for k, b, d in zip(key, base, dir_, strict=True)
            if b.endswith(".Rd") and _basename(d) == "man"
        )
    )
    r_pkg = union(
        intersect(in_dir(["DESCRIPTION"]), union(in_dir(["NAMESPACE"]), r_dirs)),
        intersect(r_dirs, rd_dirs),
    )
    # b. Python package; pyproject.toml only next to a folder with __init__.py, directly
    # or in src/
    init_dirs = _unique(k for k, b in zip(key, base, strict=True) if b == "__init__.py" and k[1])
    in_src = [k for k in init_dirs if _basename(_dirname(k[1])) == "src"]
    py_pkg = union(
        in_dir(["setup.py", "setup.cfg"]),
        intersect(in_dir(["pyproject.toml"]), [*parent(init_dirs), *parent(parent(in_src))]),
    )
    # a package that a workflow beside it runs (a Snakefile, targets) is the analysis
    # written as a package of commands, not software of its own (and so is a package
    # nested in it)
    workflow = in_dir(_SW_WORKFLOW)
    if workflow:

        def run_by_workflow(k: tuple[str, str]) -> bool:
            return any(
                wr == k[0] and (not wd or k[1] == wd or k[1].startswith(wd + "/"))
                for wr, wd in workflow
            )

        r_pkg = [k for k in r_pkg if not run_by_workflow(k)]
        py_pkg = [k for k in py_pkg if not run_by_workflow(k)]
    # c. web application
    web = in_dir(["manage.py"])
    # d. compiled software
    compiled = in_dir(_SW_COMPILED)
    # e. a copy of a released tool
    tool = _released_tools(listed, key, r_pkg + py_pkg)
    # one type per folder, the first of: a tool (cutadapt-1.1 is also a Python package), a
    # web application, a package, compiled software
    typed: dict[tuple[str, str], str] = {}
    for ks, typ in (
        (tool, "tool"),
        (web, "web_app"),
        (r_pkg, "r_package"),
        (py_pkg, "py_package"),
        (compiled, "compiled"),
    ):
        for k in ks:
            typed.setdefault(k, typ)
    names = _repro_sw_name([k[1] for k in typed], [k[0] for k in typed])
    return [_Root(k[0], k[1], typ, nm) for (k, typ), nm in zip(typed.items(), names, strict=True)]


def _released_tools(
    listed: _Listed, key: Sequence[tuple[str, str]], pkg_roots: Sequence[tuple[str, str]]
) -> list[tuple[str, str]]:
    """Step 2e: the folders (and archives) that are a copy of a released tool."""
    all_dirs: dict[tuple[str, str], None] = {}
    for r, d in _unique(k for k in key if k[1]):
        parts = d.split("/")
        for j in range(1, len(parts) + 1):
            all_dirs[(r, "/".join(parts[:j]))] = None
    dirs = list(all_dirs)
    dnames = [_basename(d) for _, d in dirs]
    is_archive = grepl(_SW_ARCHIVE_EXT, dnames, ignore_case=True)
    stripped = sub(_SW_ARCHIVE_EXT, "", dnames, ignore_case=True)
    ends_in_version = grepl(_SW_VERSION_END, dnames)
    stripped_version = grepl(_SW_VERSION_END, stripped)
    versioned = [
        k
        for k, v, a, sv in zip(dirs, ends_in_version, is_archive, stripped_version, strict=True)
        if v or (a and sv)
    ]
    out: list[tuple[str, str]] = []
    for repo, d in versioned:
        # a released package (cutadapt-1.1, mapboxer_0.4.0.tar.gz/mapboxer) stays a
        # package: it may be the one the paper presents, with its examples
        if any(r == repo and (pd_ == d or _dirname(pd_) == d) for r, pd_ in pkg_roots):
            continue
        in_repo = listed.paths_by_repo.get(repo, [])
        prefix = d + "/"
        inside = [p for p in in_repo if p.startswith(prefix)]
        # a release of a GitHub repository (owner/repo-v1.0.zip/owner-repo-1a2b3c4) is how
        # Zenodo keeps the authors' own code
        if any(grepl("^[^/]+-[0-9a-f]{7}/", p[len(d) + 1 :]) for p in inside):
            continue
        b = [_basename(p) for p in inside]
        program = (
            any(x in _SW_PROGRAM_FILES for x in b)
            or any(p.startswith(d + "/bin/") for p in inside)
            or any(grepl(_SW_PROGRAM_EXT, b, ignore_case=True))
        )
        if not program:
            continue
        # the authors' own code, released as analysis-v1.0, holds all the code there is
        archive = str(
            sub("^(.*" + _SW_ARCHIVE_EXT.removesuffix("$") + ")/.*$", r"\1", d, ignore_case=True)
        )
        outside = [
            p for p in in_repo if not p.startswith(archive + "/") and not p.startswith(prefix)
        ]
        if any(grepl(r"\.(r|rmd|qmd|py|ipynb)$", outside, ignore_case=True)):
            out.append((repo, d))
    return out


def _repro_sw_name(root: Sequence[str], repo: Sequence[str | None]) -> list[str | None]:
    """Port of R/reproducibility_check_software.R::.repro_sw_name().

    The software's name: its folder, without the owner and commit that GitHub's archives
    add (``owner/repo-v1.0.zip/owner-repo-1a2b3c4``), or the repository's name for a root
    at the top of the repository.
    """
    out: list[str | None] = []
    for rt, rp in zip(root, repo, strict=True):
        nm = str(sub(_SW_ARCHIVE_EXT, "", _basename(rt), ignore_case=True))
        owner = _basename(_dirname(_dirname(rt)))
        if grepl("-[0-9a-f]{7}$", nm) and owner and owner != "." and nm.startswith(owner + "-"):
            nm = str(sub("-[0-9a-f]{7}$", "", nm[len(owner) + 1 :]))
        if not rt:
            nm = rp or ""
        out.append(nm or None)
    return out


# ---------------------------------------------------------------------------
# stage 1, steps 3 to 5: where the file sits
