def _basename(p: str) -> str:
    """R ``basename()`` of a ``/``-separated path (a trailing ``/`` is ignored)."""
    return p.rstrip("/").rpartition("/")[2]


def _dirname(p: str) -> str:
    """R ``dirname()`` of a ``/``-separated path (``"."`` when there is no folder)."""
    p = p.rstrip("/")
    if "/" not in p:
        return "."
    return p.rpartition("/")[0].rstrip("/") or "/"


def _norm_path(p: str) -> str:
    """``sub("^(\\./|/)+", "", gsub("\\\\", "/", p))``: a deposit path without ``./`` or ``/``."""
    return str(sub(r"^(\./|/)+", "", p.replace("\\", "/")))


def _unique(xs: Iterable[Any]) -> list[Any]:
    """R ``unique()`` (first-appearance order)."""
    return list(dict.fromkeys(xs))


def _has(pattern: str, lines: Sequence[str]) -> bool:
    """``any(grepl(pattern, lines, perl = TRUE))``."""
    return any(grepl(pattern, list(lines), perl=True))


def _split_lines(x: Any) -> list[str]:
    """``unlist(strsplit(as.character(x %||% character(0)), "\\n", fixed = TRUE))``.

    Missing values are dropped (R keeps them as ``NA`` and drops them after ``iconv``).
    """
    if x is None:
        return []
    items = [x] if isinstance(x, str) else list(x)
    out: list[str] = []
    for item in items:
        s = as_str(item)
        if s is not None:
            out.extend(p for p in strsplit(s, "\n", fixed=True) if p is not None)
    return out


def _drop_invalid(lines: Iterable[str]) -> list[str]:
    """``iconv(x, "", "UTF-8", sub = "")``: bytes that are not UTF-8 are dropped.

    Invalid bytes reach Python as surrogate escapes.
    """
    return [_SURROGATES.sub("", s) if _SURROGATES.search(s) else s for s in lines]


def _code_items(code_text_list: Any, n: int) -> list[Any]:
    """The per-script code of a list or a mapping, one entry per script."""
    items = (
        list(code_text_list.values())
        if isinstance(code_text_list, Mapping)
        else list(code_text_list)
    )
    return items[:n] + [None] * (n - len(items))


