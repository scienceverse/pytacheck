def _repro_sw_links(
    path: str,
    code: Sequence[str],
    text: Sequence[str],
    ctx: _Context,
    place: _Place,
    repo: str | None,
) -> list[str]:
    """Port of R/reproducibility_check_software.R::.repro_sw_links().

    Stage 2: what links a script inside software to the paper's results; the names of the
    signals found (``paper_names_it``, ``appendix``, ``names_results``, ``readme``,
    ``data``), none when nothing does. *code* is the code that runs, *text* all the
    script's text.
    """
    links: list[str] = []
    base = _basename(path)
    # 2. the paper names the code, or an appendix the code names
    if ctx.paper:
        if _sw_named_in(ctx.paper, path, place.root_name, repo):
            links.append("paper_names_it")
        if any(a in ctx.paper for a in _sw_appendix([s.lower() for s in text])):
            links.append("appendix")
    # 3. the code names the paper's figures or tables
    if _sw_names_results(text):
        links.append("names_results")
    # 4. a README maps it to the paper
    if _sw_readme_maps(ctx.readme, base):
        links.append("readme")
    # 5. it reads the paper's data; a file of that name that the software itself ships
    # (rcoalescence's vignettes/images/ beside a copy elsewhere) is its own
    own = ctx.own_data(place.root_repo or "", place.root or "") - ctx.named
    if _sw_reads_paper_data([s.lower() for s in code], ctx.data_by_ext, own):
        links.append("data")
    return links


def _sw_escape(x: str) -> str:
    """``.repro_sw_escape()``: *x* with the characters of a regular expression escaped."""
    return str(gsub(r"([][{}()+*^$|\\?.])", r"\\\1", x))


def _sw_specific(x: str) -> bool:
    """``.repro_sw_specific()``: a name specific enough that the paper naming it means this file.

    With a digit or an underscore, or two capitalised words, and at least 6 letters (a
    hyphen is not enough: "step-by-step" is also a phrase).
    """
    return (
        len(x) >= 6
        and bool(grepl("[0-9_]", x) or grepl("[a-z][A-Z]", x))
        and x.lower() not in _SW_SPECIFIC_NOT
    )


def _sw_counts(paper: str, pattern: str) -> bool:
    """Whether *pattern* occurs in *paper* other than where it only points to documentation.

    A mention counts unless what is around it (its sentence, a figure caption next to it is
    not about it) only points to documentation ("the main tutorial", "see the vignette for
    more details") and says nothing of results (a figure, a table, an analysis, an
    appendix).
    """
    for at, _length in gregexpr_all(pattern, paper, perl=True):
        before = paper[max(1, at - 200) - 1 : at]
        after = paper[at : at + 200]
        found = gregexpr_all(_SW_LAST_SENTENCE, before)
        around = (before[found[0][0] + 1 :] if found else before) + str(sub(r"\.\s.*$", "", after))
        if not grepl(
            "tutorial|for (more )?details|detailed description|step-by-step|documentation|"
            "vignettes? of the package|main vignette|retrieved from",
            around,
            perl=True,
        ) or grepl(
            r"\b(fig(ure)?s?\.?|tables?) ?s?[0-9]|\bappendix|\bsupplement|reproduc|"
            r"\bour (analys[ie]s|results)",
            around,
            perl=True,
        ):
            return True
    return False


def _sw_named_in(paper: str, path: str, root_name: str | None, repo: str | None) -> bool:
    """``.repro_sw_named_in()``: signal 2, the paper names the script.

    With its extension, or a specific name without it, or the folder it sits in when that
    name is specific and not the software's own name; or its rendered page
    (``data-sources.html``, a website's ``articles/data-sources``).
    """
    base = _basename(path)
    stem = str(sub(r"\.[^.]+$", "", base))
    folder = _basename(_dirname(path))
    own = {x.lower() for x in (root_name, repo) if x is not None}

    def word(x: str) -> bool:
        return _sw_counts(paper, "(^|[^a-z0-9_.-])" + _sw_escape(x.lower()) + "($|[^a-z0-9_-])")

    if len(base) >= 5 and word(base):
        return True
    # a name of its own, not the software's (a package's main vignette, GIFT.Rmd)
    if _sw_specific(stem) and stem.lower() not in own and word(stem):
        return True
    # the rendered vignette or notebook: data-sources.html, a package website's
    # articles/data-sources
    if len(stem) >= 4 and (
        word(stem + ".html")
        or word(stem + ".pdf")
        or _sw_counts(paper, "(articles|vignettes)/" + _sw_escape(stem.lower()) + "($|[^a-z0-9_-])")
    ):
        return True
    return folder != "." and _sw_specific(folder) and folder.lower() not in own and word(folder)


def _sw_appendix(lc: Sequence[str]) -> list[str]:
    """``.repro_sw_appendix()``: the appendices and supplements a script names (``appendix s2``)."""
    found = regextract_all(
        r"\b(appendix|supplementary (material|information|file|text)|supporting information|"
        r"online resource) ?s?[0-9]+\b",
        list(lc),
    )
    return _unique(str(gsub(r"\s+", " ", x)) for xs in found for x in xs)


def _sw_names_results(code: Sequence[str]) -> list[str]:
    """``.repro_sw_names_results()``: signal 3, the lines in which the code names the paper's figures or tables.

    A comment that says which figure or table of the paper it makes, or a file it writes
    named after one (``fig3.png``, ``table_1.csv``). A vignette's own captions ("Figure
    1. The example data") and figure counters do not count.
    """
    code = list(code)
    # a file name that starts with the figure or table (fig3.png, results/Table_S1.csv,
    # map_fig2.pdf), not one that only holds the word (Raven's x.Table.1.selections.txt)
    out_file = grepl(
        """["'/_-](fig|figure|tab|table)[ _-]?s?[0-9]+[a-z]?([_-][^"'/]*)?"""
        r"""\.(png|pdf|jpe?g|tiff?|svg|eps|csv|xlsx?|docx?|html|txt|rds)["']""",
        code,
        ignore_case=True,
        perl=True,
    )
    # showing a picture is not making one (knitr::include_graphics("images/runauto_fig1.png"))
    shows = grepl(r"include_graphics|readpng|imread|image_read|!\[", code, ignore_case=True)
    # text that says it is about the paper's figure ("Figure 3 of the paper")
    paper_fig = grepl(
        r"\b(fig(ure)?s?\.?|table)\s*s?[0-9]+[a-z]?\s+(of|in|from) (the|our|this) "
        r"(main )?(paper|manuscript|article|main text|publication)",
        code,
        ignore_case=True,
        perl=True,
    )
    is_comment = grepl(r"^\s*(#|//)", code)
    names_fig = grepl(
        r"\b(fig(ure)?s?\.?|table|appendix|supplementary (fig(ure)?|table))\s*s?[0-9]+[a-z]?\b",
        code,
        ignore_case=True,
        perl=True,
    )
    caption = grepl(r"fig\.cap|caption|captioner", code, ignore_case=True)
    return [
        line
        for line, f, sh, pf, c, nf, ca in zip(
            code, out_file, shows, paper_fig, is_comment, names_fig, caption, strict=True
        )
        if (f and not sh) or (c and nf and not ca) or pf
    ]


def _sw_readme_maps(readme: Sequence[Sequence[str]], base: str) -> bool:
    """``.repro_sw_readme_maps()``: signal 4, a README line names the script together with a figure, table or section of the paper."""
    if not readme:
        return False
    b = base.lower()
    stem = str(sub(r"\.[^.]+$", "", b))
    specific = _sw_specific(stem)
    for lines in readme:
        hit = [k for k, ln in enumerate(lines) if b in ln or (specific and stem in ln)]
        if not hit:
            continue
        near = sorted({min(len(lines) - 1, max(0, k + d)) for k in hit for d in (-1, 0, 1)})
        if _has(
            r"\b(fig(ure)?s?\.?|table|appendix|supplement[a-z]*)\s*s?[0-9]+|"
            r"\b(results?|analys[ie]s) (in|of|for) the (paper|manuscript|article)",
            [lines[k] for k in near],
        ):
            return True
    return False


def _sw_reads_paper_data(
    lc: Sequence[str],
    data_by_ext: Mapping[str, Sequence[str]],
    excluded: frozenset[str] = frozenset(),
) -> bool:
    """``.repro_sw_reads_paper_data()``: signal 5, the code names a data file deposited with the paper.

    Other than through ``system.file()`` or a package's example data. *lc* is the code in
    lower case. R takes the list of data names; here they come grouped by extension (a name
    can only be in the code when its ``.ext`` is), minus the *excluded* names, so a script
    is not searched for thousands of names.
    """
    if not data_by_ext or not lc:
        return False
    keep = [
        s for s in lc if not grepl(r"system\.file|extdata|pkg_resources|importlib\.resources", s)
    ]
    txt = "\n".join(keep)
    for ext, names in data_by_ext.items():
        if "." + ext in txt and any(f in txt for f in names if f not in excluded):
            return True
    return False


