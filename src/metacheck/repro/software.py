"""The files of a deposit that belong to software, not to the paper's analysis.

Port of metacheck's ``R/reproducibility_check_software.R`` (and the small helpers of
``R/reproducibility_check.R`` that only it needs: :func:`_repro_is_r_test`,
:func:`_repro_is_py_test`, :func:`_repro_py_imported`).

The module reproduces a paper's results: the scripts that turn the deposit's data into
the paper's numbers and figures. Deposits also hold software: the paper's own R or
Python package, a tool the authors copied into the deposit, a web application, the
programs of a data logger. Running the files of such software says nothing about the
paper's results: a file of a package's code "runs" without doing anything, and a tool's
helper fails because it waits for arguments, a server or a device. These files get the
outcome ``not_analysis`` and are not counted as scripts (#568).

The principle: every analysis reported in the paper should be reproduced, so the
question for each script is whether it holds results that go into the paper. Outside
software, the usual analysis deposit, every script is taken to do so and runs. Inside
software, a script counts only when something links it to the paper (stage 2); a
package's vignettes and examples are mostly tutorials of the software on its own example
data.

No single signal separates the two. A package can hold the paper's analysis (a paper/
folder next to R/), an analysis deposit can hold a whole tool (a copy of cutadapt-1.1 or
of Trinity), and a tool writes R scripts of its own into the analysis folders. So every
script goes through this decision path.

Stage 1: is the file part of software?

1. What the file is, wherever it sits (:func:`_repro_software_file`):

   a. written by a program, not by the authors: its first lines say so (Rcpp's
      RcppExports.R, rstantools, protocol buffers, Django migrations: "Generated by ...
      do not edit"), or its name starts with ``__tmp`` (the R scripts Trinity writes and
      runs, __tmp_runTMM.R). Such a script outside software that reads a file is
      analysis after all: Trinity's __tmp_runTMM.R normalises the paper's data;
   b. the settings of the Sphinx documentation builder (a conf.py that names Sphinx
      settings), or a file in a docs/ folder below such a conf.py, except a notebook or a
      file in its tutorials/ or examples/, which do what a vignette does; or a template
      of roxygen2 (man-roxygen/);
   c. a part of a Django web application (it imports django or rest_framework);
   d. a script that builds, checks or packs software and reads no data
      (devtools::check() or build(), pkgdown, roxygen2, the libraries rwinlib holds for
      building a package on Windows, PyInstaller, nox);
   e. a file under .github/, .gitlab/ or .circleci/ (automatic checks);
   f. __init__.py, which makes its folder a Python package to import.

2. Which software the file sits in (:func:`_repro_software_roots`). A folder is the root
   of software when the deposit lists in that folder

   a. an R package: DESCRIPTION, with NAMESPACE or an R/ folder; or R/ next to help files
      in man/ (*.Rd), which only a package has (the listing of an archive can leave
      DESCRIPTION out);
   b. a Python package: setup.py or setup.cfg, or pyproject.toml next to a folder with
      __init__.py (an analysis can use pyproject.toml just to list the packages it
      needs); neither a. nor b. when a workflow beside it runs the package (a Snakefile,
      _targets.R, make.R, Nextflow, dvc.yaml): that is the analysis written as a package
      of commands (digitizing-the-coral-reef);
   c. a web application: manage.py (Django);
   d. compiled software: CMakeLists.txt, configure, configure.ac, meson.build,
      Cargo.toml, go.mod, pom.xml or build.gradle;
   e. a copy of a released tool: a folder, or the archive it came in, whose name ends in
      a version (trinityrnaseq_r2012-06-08.tgz) that holds the files of a program (build
      files, a bin/ folder, or code in another language than R and Python), in a
      repository that also holds R or Python code outside it; without that code, the
      folder is a release of the authors' own code (analysis-v1.0). A GitHub release kept
      on Zenodo (owner/repo-v1.0.zip/owner-repo-1a2b3c4) is the authors' own code too. A
      released package (cutadapt-1.1, mapboxer_0.4.0.tar.gz) stays a package (a. or b.):
      it may be the package the paper presents.

   A file outside every root is analysis, unless step 1 applies. A root belongs to its
   repository: a package in one repository says nothing about the files of another.

3. In a web application or a copy of a released tool, or in a root nested in one, every
   file is software: the examples of cvat-sdk inside CVAT are examples of CVAT, and
   Trinity's Analysis/ folder is Trinity's.

4. Otherwise the paper's analysis can have a folder of its own inside the software:
   paper/, manuscript/, analysis/, reproduc*/, replication/, figures/, results/. A file
   in such a folder is analysis (unless the folder is inside tests/: tests/analysis/
   holds tests): the folder's name links it to the paper's results.

5. Roots can be nested (ESP-IDF holds a compiled project per example and per component).
   A file is software when, seen from any root it is in, the outermost first, it is:

   a. in a tests/ folder;
   b. in compiled software, in a folder these projects use for their own code and tools
      (tools/, components/, src/, lib/, test/, examples/, docs/, ...), or in a compiled
      project nested in it (a module of a 3D Slicer extension);
   c. in an R package, in R/, src/, tools/ or exec/: the package's code;
   d. in a Python package, in a folder with __init__.py, src/ or bin/ (the package's
      code), or in docs/ or ci/.

Stage 2 (:func:`_repro_sw_links`): the other files of software (vignettes, examples,
demos, scripts, notebooks, data-raw, inst/, loose scripts, and in compiled software the
files outside its code folders) count as the paper's analysis only when at least one of
these links them to the paper; otherwise they are ``not_analysis`` ("it documents or
tests the software").

6. a. the paper names the script (its file name; its name without extension, or its
      folder, when that name is specific: a digit, an underscore or two capitalised
      words, and not the software's own name), or its rendered page (data-sources.html,
      a website's articles/data-sources); not where the paper only points to it as
      documentation ("the main tutorial", "see the vignette for more details") without
      naming a figure, table, appendix or the results; or an appendix or supplement that
      the script names ("Appendix S2");
   b. the script names the paper's figures or tables: a comment that says which figure or
      table it makes ("# Figure 3", "## Table S2"), text that says so ("Figure 3 of the
      paper"), or a file it writes named after one (fig3.png, table_1.csv). A vignette's
      captions (fig.cap, a caption function) do not count;
   c. a README of the deposit names the script next to a figure, table, appendix or
      supplement, or "the results of the paper";
   d. the code names a data file deposited with the paper: a data file outside every
      software folder (the data of a package's own examples sit inside it), or one
      inside that the paper itself names.

   Whether the numbers a script prints match the paper is not used here: the module
   reports that after a run.

7. A script left unlinked is linked after all, in the same repository, when a script that
   runs reads a file it writes, source()s it or imports it; when it reads a file a script
   that runs writes; or when it source()s or imports a script linked to the paper; and so
   on along the chain (:func:`_repro_sw_chain`). The pipeline that feeds a figure is part
   of the analysis even when nothing names it. A name built from a pattern
   ("{metric}_per_hour.csv") matches the names it can stand for.

What the paths cannot tell is whether a package or tool is the paper's own. A tool's
repository without any of the files of step 2 (PyRate, a set of Python programs) is
treated as analysis.

Python notes. R's data frames of this file's internals are small typed records
(:class:`_Listed`, :class:`_Root`, :class:`_Place`, :class:`_Context`); the entry points
return what R returns (a table for :func:`_repro_software_kind`, character vectors as
lists of ``str | None``). Paths of the deposit are always ``/``-separated.
"""

