def _repro_software_file(path: str, code: Sequence[str], listed: _Listed) -> str | None:
    """Port of R/reproducibility_check_software.R::.repro_software_file().

    Step 1: what the file itself is. Returns the kind (``generated``, ``docs``,
    ``web_app``, ``build``, ``ci`` or ``package_init``) or ``None``. R returns it as
    ``list(kind = ...)``.
    """
    base = _basename(path).lower()
    is_py = base.endswith(".py")
    code = _drop_invalid(code)
    if base.startswith("__tmp") or _has(
        "(?i)(generated by (using )?(rcpp|rstantools|the protocol buffer compiler|"
        "django|'django-admin|swig|cython)|this file was generated by rcpp|"
        "generated.{0,60}do not edit)",
        code[:12],
    ):
        return "generated"
    if (
        (
            base == "conf.py"
            and _has(r"(?i)(sphinx|html_theme|^\s*extensions\s*=|master_doc|source_suffix)", code)
        )
        or _sw_below_sphinx(path, listed)
        or grepl("(^|/)man-roxygen/", path)
    ):
        return "docs"
    if is_py and _has(r"^\s*(from|import)\s+(django|rest_framework)\b", code):
        return "web_app"
    if _sw_builds(code, is_py):
        return "build"
    if grepl(r"(^|/)\.(github|gitlab|circleci)/", path):
        return "ci"
    if base == "__init__.py":
        return "package_init"
    return None


def _sw_below_sphinx(path: str, listed: _Listed) -> bool:
    """``.repro_sw_below_sphinx()``: a file in a docs/ folder that holds a Sphinx conf.py.

    Its themes and extensions, but not its tutorials or examples, which do what a vignette
    does (and a notebook in the documentation is a worked example too).
    """
    if grepl(r"\.(ipynb|rmd|qmd)$", path, ignore_case=True):
        return False
    below = next((c for c in listed.sphinx_confs if path.startswith(c + "/")), None)
    if below is None:
        return False
    folders = path[len(below) + 1 :].lower().split("/")[:-1]
    return not any(grepl(_SW_KEEP_DIR, folders))


def _sw_builds(code: Sequence[str], is_py: bool) -> bool:
    """``.repro_sw_builds()``: a script that builds, checks or packs software, and reads no data (1d)."""
    code = [s for s in code if not grepl(r"^\s*#", s)]
    if is_py:
        return _has(
            r"^\s*(import|from)\s+(PyInstaller|nox|versioneer|cx_Freeze|py2exe|py2app)\b", code
        ) or _has(r"""['"]pyinstaller['"]""", code)
    # installing a package, or saving a package's data (usethis::use_data()), is what an
    # analysis does too; rwinlib holds the libraries a package needs to be built on
    # Windows (tools/winlibs.R)
    builds = _has(
        r"\b(devtools::(check|build|document|build_manual|build_vignettes|release|"
        r"submit_cran)|pkgdown::build_[a-z]+|roxygen2::roxygeni[sz]e|"
        r"usethis::use_(?!data)[a-z_]+|Rcpp::compileAttributes)\s*\(",
        code,
    ) or _has(r"github\.com/rwinlib/", code)
    return builds and not _sw_reads_data(code)


def _sw_reads_data(code: Sequence[str]) -> bool:
    """``.repro_sw_reads_data()``: whether R code reads a data file."""
    return _has(
        r"\b(read[._](csv2?|table|delim|tsv|xlsx?|excel|dta|sav|spss|stata|fwf|rds|sas)|"
        r"readRDS|readxl::|fread|load|st_read|readOGR|raster|rast|nc_open|vroom|"
        r"read_sf|readLines|scan)\s*\(",
        code,
    )


