@overload
def _repro_is_r_test(paths: str) -> bool: ...
@overload
def _repro_is_r_test(paths: list[str | None]) -> list[bool]: ...
def _repro_is_r_test(paths: str | Sequence[str | None]) -> bool | list[bool]:
    """Port of R/reproducibility_check.R::.repro_is_r_test().

    A package's own tests: run on their own, they test whether the package is installed,
    not whether the paper's analysis reproduces. A path (or each path of a list) is a test
    when it sits in ``tests/testthat/`` or is ``tests/testthat.R``-like.
    """
    out = grepl(r"(^|/)tests/testthat(/|\.[Rr]$)", gsub(r"\\", "/", paths))
    return out if isinstance(paths, str) else list(out)


def _repro_is_py_test(path: str, code_text: str | Sequence[str | None]) -> bool:
    """Port of R/reproducibility_check.R::.repro_is_py_test().

    The same for Python, and the file that installs a package. A name alone is not
    enough: ``model_test.py`` and ``predict_test.py`` can be analyses. A test imports a
    test framework (or defines ``test_*`` functions in a tests/ folder), ``setup.py``
    imports setuptools or distutils and calls ``setup()``.
    """
    lines = [code_text] if isinstance(code_text, str) else [s for s in code_text if s is not None]
    path = str(gsub(r"\\", "/", path)).lower()
    base = _basename(path)
    if not base.endswith(".py"):
        return False
    if base == "conftest.py":
        return True
    if base == "setup.py":
        return _has(r"^\s*(import|from)\s+(setuptools|distutils)\b", lines) and _has(
            r"\bsetup\s*\(", lines
        )
    in_tests = bool(grepl("(^|/)tests?/", path))
    named = bool(grepl(r"^test_.*\.py$|_test\.py$|^tests?\.py$", base))
    return (
        (named or in_tests)
        and _has(r"^\s*(import|from)\s+(pytest|unittest|nose|django\.test)\b", lines)
    ) or (in_tests and _has(r"^\s*def\s+test_", lines))


def _repro_py_import_names(code_text_list: Sequence[Sequence[str | None]]) -> list[list[str]]:
    """Port of R/reproducibility_check.R::.repro_py_import_names().

    The module names each Python file imports (``a.b`` gives ``a`` and ``b``; ``from a
    import b`` gives ``a`` and ``b``), one list per file; comment lines are skipped.
    """
    return [_py_import_names_one(txt) for txt in code_text_list]


def _py_import_names_one(txt: Sequence[str | None]) -> list[str]:
    """The module names one Python file imports (see :func:`_repro_py_import_names`)."""
    lines = [s for s in txt if s is not None and not grepl(r"^\s*#", s)]
    names: list[str] = []
    for m in regexec(r"^\s*import\s+([A-Za-z0-9_., ]+)", lines):
        if len(m) > 1:
            names.extend(
                str(trimmed)
                for part in strsplit(m[1], ",")
                if (trimmed := str(sub(r"\s+as\s+.*$", "", part)).strip())
            )
    for m in regexec(r"^\s*from\s+([A-Za-z0-9_.]+)\s+import\s+([A-Za-z0-9_, ()*]+)", lines):
        if len(m) > 2:
            names.append(m[1])
            names.extend(
                str(sub(r"\s+as\s+.*$", "", part)).strip()
                for part in strsplit(str(gsub(r"[()]", "", m[2])), ",")
            )
    return _unique(piece for name in names for piece in strsplit(name, ".", fixed=True))


def _repro_py_imported(
    code_text_list: Mapping[str, Sequence[str | None]], paths: Sequence[str | None] | None = None
) -> dict[str, list[str]]:
    """Port of R/reproducibility_check.R::.repro_py_imported().

    Python files that other files of the run import. A module such as
    ``utils/data_handling.py`` is not a script: it defines functions for the scripts that
    import it, and run on its own it does nothing, or fails on code meant to run only when
    imported. Like an R script another script ``source()``s, such a file is not run on its
    own. A file with an ``if __name__ == "__main__":`` block is a script too, and still
    runs.

    *code_text_list* maps the Python files' names to their code; *paths* are the files'
    paths in the package (same order), for dotted imports (``from utils.data_handling
    import x``), and default to the names. Returns a dict (R's named list): for each
    imported file, the files that import it, in file order. A package's ``__init__.py`` is
    imported by its folder's name. Of several files with one module name, a file imports
    the one beside it, or the one in the folder it names (``from a.utils import x``). Only
    a ``.py`` file can be imported (``import audio`` names a module, not ``audio.ipynb``).
    """
    fns = list(code_text_list)
    if not fns:
        return {}
    if paths is None:
        paths = fns
    full = [
        fn if is_missing(p) or not p else str(p).replace("\\", "/")
        for fn, p in zip(fns, paths, strict=True)
    ]
    stem = [str(sub(r"([^.]+)\.[[:alnum:]]+$", r"\1", _basename(p))) for p in full]
    # a package's __init__.py is imported by the package's (its folder's) name
    for i, p in enumerate(full):
        if stem[i] == "__init__":
            stem[i] = _basename(_dirname(p))
    imports = _repro_py_import_names([code_text_list[fn] for fn in fns])
    is_main = [
        _has(
            r"""^\s*if\s+__name__\s*==\s*['"]__main__['"]""",
            [s for s in code_text_list[fn] if s is not None],
        )
        for fn in fns
    ]
    dirs = [_dirname(p) for p in full]
    importers: dict[str, list[int]] = defaultdict(list)
    for j, names in enumerate(imports):
        for name in names:
            importers[name].append(j)
    seen_stem: set[str] = set()
    repeated_stem: set[str] = set()
    for s in stem:
        (repeated_stem if s in seen_stem else seen_stem).add(s)
    importable = grepl(r"\.py$", full, ignore_case=True)
    out: dict[str, list[str]] = {}
    for i, fn in enumerate(fns):
        if is_main[i] or stem[i] in ("", ".") or not importable[i]:
            continue
        repeated = stem[i] in repeated_stem
        by = [
            fns[j]
            for j in importers.get(stem[i], ())
            if j != i and (not repeated or dirs[j] == dirs[i] or _basename(dirs[i]) in imports[j])
        ]
        if by:
            out[fn] = _unique(by)
    return out


