def _repro_software_kind(
    paths: Sequence[str | None],
    code_text_list: Sequence[Any] | Mapping[str, Any],
    structure_df: pd.DataFrame | None = None,
    repos: Sequence[str | None] | None = None,
    paper_text: str | Sequence[str] | None = None,
    raw_text_list: Sequence[Any] | Mapping[str, Any] | None = None,
) -> pd.DataFrame:
    """Port of R/reproducibility_check_software.R::.repro_software_kind().

    The decision path of the module docstring for each script. *paths* are the scripts'
    paths in their repository, *code_text_list* their code (a list of lines, or one text,
    per script), *structure_df* the files the deposit lists (``file_path`` or
    ``file_name``, ``repo_name`` and ``file_location``, as data_check's structure table),
    *repos* each script's repository (``None`` when unknown), *paper_text* the paper's text
    (:func:`_repro_paper_text`) and *raw_text_list* each script's whole text (code and the
    text between the code of a notebook or R Markdown file).

    Returns a table of one row per script with the string columns ``kind`` (``None`` for
    analysis, else ``generated``, ``docs``, ``web_app``, ``build``, ``ci``,
    ``package_init``, ``package``, ``test``, ``tool`` or ``unlinked``), ``software`` (the
    name of the software, ``None`` when none is known), ``why`` (the sentence the report
    gives) and ``links`` (what links the script to the paper, ``", "``-separated codes of
    stage 2, ``None`` when nothing does).
    """
    n = len(paths)
    cols: dict[str, list[str | None]] = {
        k: [None] * n for k in ("kind", "software", "why", "links")
    }
    if not n:
        return _kind_frame(cols)
    norm = [_norm_path(as_str(p) or "") for p in paths]
    rep: list[str | None] = (
        [None] * n if not repos else [as_str(repos[i % len(repos)]) for i in range(n)]
    )
    listed = _repro_sw_listed(structure_df, norm, rep)
    roots = _repro_software_roots(listed)
    ctx = _repro_sw_context(listed, roots, paper_text)
    codes = _code_items(code_text_list, n)
    raws = _code_items(raw_text_list, n) if raw_text_list is not None else [None] * n
    for i in range(n):
        code = _drop_invalid(_split_lines(codes[i]))
        kind = _repro_software_file(norm[i], code, listed)
        place = _repro_software_place(norm[i], rep[i], roots, listed)
        in_software = place.root_name is not None
        # what links it to the paper matters only for a file of software that steps 1 to 5
        # did not already place (an example, a vignette, a loose script)
        needs_link = in_software and place.kind is None and not place.paper_dir and kind is None
        links = (
            _repro_sw_links(
                norm[i], code, _repro_sw_all_text(raws[i], norm[i], code), ctx, place, rep[i]
            )
            if needs_link
            else []
        )
        cols["links"][i] = ", ".join(links) if links else None
        hit: tuple[str | None, str | None]
        if place.kind in ("web_app", "tool"):
            # a part of a web application or of a copied tool, whatever it does
            hit = (place.kind, place.software)
        elif kind is not None:
            # what the file is; a script a program wrote that works on the paper's data
            # (Trinity's __tmp_runTMM.R in an analysis folder) is analysis
            if kind == "generated" and not in_software and _sw_reads_any(code):
                hit = (None, None)
            else:
                hit = (kind, place.root_name)
        elif place.kind is not None:
            hit = (place.kind, place.software)
        elif in_software and not place.paper_dir and not links:
            # 6. an example, vignette, notebook or loose script of software that nothing
            # links to the paper's results
            hit = ("unlinked", place.root_name)
        else:
            hit = (None, None)
        cols["kind"][i], cols["software"][i] = hit
    cols["why"] = _repro_software_why(cols["kind"], cols["software"])
    return _kind_frame(cols)


def _kind_frame(cols: Mapping[str, list[str | None]]) -> pd.DataFrame:
    """The table of :func:`_repro_software_kind`: kind, software, why, links."""
    return pd.DataFrame(
        {k: pd.array(cols[k], dtype="string") for k in ("kind", "software", "why", "links")}
    )


def _repro_paper_text(paper: Any) -> str:
    """Port of R/reproducibility_check_software.R::.repro_paper_text().

    The paper's text (the ``text`` column of its text table, joined by newlines), ``""``
    when there is none (a local folder checked on its own).
    """
    try:
        txt = paper.text["text"]
    except (AttributeError, KeyError, TypeError):
        return ""
    return "\n".join(s for s in (as_str(v) for v in txt) if s is not None)


def _repro_sw_context(
    listed: _Listed, roots: Sequence[_Root], paper_text: str | Sequence[str] | None = None
) -> _Context:
    """Port of R/reproducibility_check_software.R::.repro_sw_context().

    What stage 2 needs once per deposit: the paper's text in lower case with single
    spaces, the lines (lower case) of the deposit's README files that are on disk and not
    over 2 MB, and the names of the data files deposited with the paper.
    """
    if paper_text is None:
        joined = ""
    elif isinstance(paper_text, str):
        joined = paper_text
    else:
        joined = " ".join(str(s) for s in paper_text)
    paper = str(gsub(r"\s+", " ", joined)).lower()
    readme: list[list[str]] = []
    for p, loc in zip(listed.path, listed.location, strict=True):
        if not loc or not grepl("^readme", _basename(p), ignore_case=True):
            continue
        try:
            if not os.path.exists(loc) or os.path.getsize(loc) > 2e6:
                continue
            with open(loc, "rb") as fh:
                text = fh.read().decode("utf-8", "ignore")
        except OSError:
            continue
        lines = re.split(r"\r\n|\n|\r", text)
        if lines and lines[-1] == "":
            lines.pop()
        readme.append([s.lower() for s in lines])
    data, named = _repro_sw_paper_data(listed, roots, paper)
    is_data = grepl(_SW_DATA_EXT, listed.path, ignore_case=True)
    data_files = [(r, p) for r, p, d in zip(listed.repo, listed.path, is_data, strict=True) if d]
    return _Context(paper, readme, data, frozenset(named), data_files)


def _repro_sw_paper_data(
    listed: _Listed, roots: Sequence[_Root], paper: str = ""
) -> tuple[list[str], list[str]]:
    """Port of R/reproducibility_check_software.R::.repro_sw_paper_data().

    The names (lower case) of the data files deposited with the paper: every data file of
    the deposit outside software (a package's data/, extdata/ or tests/ hold the data of
    its own examples), and a data file inside software that the paper names (its data
    availability statement). Returns ``(names, named)``: all the names of at least 5
    characters, and those inside software the paper names (R's ``"named"`` attribute).
    """
    is_data = grepl(_SW_DATA_EXT, listed.path, ignore_case=True)
    not_data = grepl(_SW_NOT_DATA, listed.base, ignore_case=True)
    roots_by_repo: dict[str, list[str]] = defaultdict(list)
    for r in roots:
        roots_by_repo[r.repo].append(r.root)
    outside: list[str] = []
    inside: list[str] = []
    for k, (d, nd) in enumerate(zip(is_data, not_data, strict=True)):
        if not d or nd:
            continue
        path = listed.path[k]
        in_software = any(
            not root or path.startswith(root + "/")
            for root in roots_by_repo.get(listed.repo[k], ())
        )
        (inside if in_software else outside).append(listed.base[k].lower())
    named = [f for f in _unique(inside) if len(f) >= 8 and paper and f in paper]
    names = [f for f in _unique([*_unique(outside), *named]) if len(f) >= 5]
    return names, named


def _sw_reads_any(code: Sequence[str]) -> list[str]:
    """``.repro_sw_reads_any()``: the files a script reads (names), from ``repro_file_io()``."""
    from metacheck.repro.core import repro_file_io

    try:
        io = repro_file_io({"x": list(code)}, "R")
    except Exception:  # R: tryCatch(..., error = function(e) NULL)
        return []
    if io is None or not len(io):
        return []
    return [str(v) for v in (io["reads"].iloc[0] or [])]


def _repro_sw_all_text(raw: Any, path: str, code: Sequence[str]) -> list[str]:
    """Port of R/reproducibility_check_software.R::.repro_sw_all_text().

    All the text of a script: its code with its comments and, for a notebook or an R
    Markdown file, the text between the code (*code* holds code only). *raw* is the whole
    text (lines or one text); a notebook's cells are read from its JSON. Without *raw*
    (or when the notebook cannot be read) the code is the text.
    """
    lines = _split_lines(raw)
    if not lines:
        return list(code)
    if grepl(r"\.ipynb$", path, ignore_case=True):
        try:
            nb = json_loads("\n".join(lines))
        except ValueError:
            return list(code)
        cells = json_field(nb, "cells")
        if not isinstance(cells, list):
            return list(code)
        lines = []
        for cell in cells:
            src = json_field(cell, "source")
            text = "".join(src) if isinstance(src, list) else str(src or "")
            lines.extend(_split_lines(text))
    return _drop_invalid(lines)


