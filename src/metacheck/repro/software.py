class _NameIndex:
    """Which scripts hold a name, where a name built from a pattern stands for others.

    A name with ``{...}``, ``%d``-style or ``*`` parts ("{metric}_per_hour.csv") matches
    any name it can stand for, in either direction.
    """

    def __init__(self, names_by_script: Sequence[Sequence[str]]) -> None:
        self.exact: dict[str, list[int]] = defaultdict(list)
        self.entries: list[tuple[int, str]] = []
        self.patterns: list[tuple[int, Any]] = []
        for j, names in enumerate(names_by_script):
            for name in _unique(names):
                self.exact[name].append(j)
                self.entries.append((j, name))
                rx = _name_regex(name)
                if rx is not None:
                    self.patterns.append((j, rx))

    def find(self, names: Sequence[str]) -> set[int]:
        """The scripts that hold a name that can be one of *names*."""
        out: set[int] = set()
        for x in names:
            out.update(self.exact.get(x, ()))
            rx = _name_regex(x)
            if rx is not None:
                out.update(j for j, y in self.entries if rx.search(y))
        if self.patterns:
            out.update(j for j, rx in self.patterns if any(rx.search(x) for x in names))
        return out


def _name_regex(name: str) -> Any:
    """The regex a name built from a pattern stands for, ``None`` for a plain name."""
    if not grepl(r"\{|%|\*", name):
        return None
    x = str(gsub(r"([.+^$()|\[\]\\])", r"\\\1", name, perl=True))
    x = str(gsub(r"\{[^}]*\}|%[0-9.]*[sdif]|\*", ".+", x, perl=True))
    try:
        return compile_r("^" + x + "$", perl=True)
    except RegexError:
        return None


def _str_list(v: Any) -> list[str]:
    """A list-column cell as lower-case strings (``NA`` and missing cells give none)."""
    if v is None or (not isinstance(v, list | tuple) and is_missing(v)):
        return []
    items = [v] if isinstance(v, str) else list(v)
    return [s.lower() for s in (as_str(x) for x in items) if s is not None]


def _repro_sw_chain(
    kind: Sequence[str | None],
    file_names: Sequence[str],
    io: pd.DataFrame | None = None,
    imported: Mapping[str, Sequence[str]] | None = None,
    repos: Sequence[str | None] | None = None,
    links: Sequence[str | None] | None = None,
) -> list[str | None]:
    """Port of R/reproducibility_check_software.R::.repro_sw_chain().

    Step 7, after stage 2: the scripts the paper's analysis depends on. Nothing may name
    the pipeline that feeds a figure: in FluxRGNN, run_baselines.py writes the summary.csv
    that run_experiments.py reads, and evaluate_performance.py writes the
    rmse_per_hour.csv a notebook reads as "{metric}_per_hour.csv". So a script left
    unlinked by stage 2 is linked after all, in the same repository, when

    a. a script that runs (kind ``None``) reads a file it writes, ``source()``s it or
       imports it: the analysis needs it;
    b. it reads a file that a script that runs writes: it works on the analysis's results;
    c. it ``source()``s or imports a script linked to the paper (a link of stage 2, or of
       this step): it drives that part of the analysis;

    repeated, so the whole chain is linked. A name built from a pattern
    ("{metric}_per_hour.csv", "fig_%d.png") matches any name it can stand for.

    *kind* is :func:`_repro_software_kind`'s column, *links* its column of links (``None``
    when none), *file_names* the scripts' names (as in *io*), *io* ``repro_file_io()``'s
    table (``file_name``, ``reads``, ``writes``, ``sources``), *imported*
    :func:`_repro_py_imported`'s dict (imported file -> the files that import it) and
    *repos* each script's repository. Returns, per script, how it is linked ("run.py needs
    what it makes"; ``None`` when not linked).
    """
    n = len(kind)
    through: list[str | None] = [None] * n
    if "unlinked" not in kind or io is None or not len(io):
        return through
    repo = ["" if is_missing(r) else str(r) for r in (repos if repos is not None else [""] * n)]
    imported = imported or {}
    first: dict[str, int] = {}
    for k, f in enumerate(io["file_name"]):
        first.setdefault(str(f), k)

    def cell(col: str, i: int) -> list[str]:
        at = first.get(file_names[i])
        return [] if at is None or col not in io.columns else _str_list(io[col].iloc[at])

    reads = [cell("reads", i) for i in range(n)]
    writes = [cell("writes", i) for i in range(n)]
    sources = [cell("sources", i) for i in range(n)]

    def stem(f: str) -> str:
        return _basename(f.replace("\\", "/")).lower()

    readers, writers = _NameIndex(reads), _NameIndex(writes)
    sourced_by: dict[str, list[int]] = defaultdict(list)
    for j, names in enumerate(sources):
        for name in names:
            sourced_by[name].append(j)
    by_name: dict[str, list[int]] = defaultdict(list)
    by_stem: dict[str, list[int]] = defaultdict(list)
    for j, f in enumerate(file_names):
        by_name[f].append(j)
        by_stem[stem(f)].append(j)
    # what u imports: the files whose importers include u
    imports_of: dict[str, list[str]] = defaultdict(list)
    for imported_file, importers in imported.items():
        for importer in importers:
            imports_of[importer].append(imported_file)
    runs = [k is None for k in kind]
    strong = [r and (links is not None and not is_missing(links[i])) for i, r in enumerate(runs)]
    while True:
        added = False
        for u in [i for i in range(n) if kind[i] == "unlinked" and through[i] is None]:

            def pick(candidates: Iterable[int], flags: list[bool], u: int = u) -> int | None:
                return min((j for j in candidates if flags[j] and repo[j] == repo[u]), default=None)

            needs = set(readers.find(writes[u]))
            needs.update(sourced_by.get(stem(file_names[u]), ()))
            for importer in imported.get(file_names[u], ()):
                needs.update(by_name.get(importer, ()))
            needed_by = pick(needs, runs)
            works_on = pick(writers.find(reads[u]), runs)
            driven = {*sources[u], *(k.lower() for k in imports_of.get(file_names[u], ()))}
            drives = pick((j for s in driven for j in by_stem.get(s, ())), strong)
            if needed_by is not None:
                through[u] = f"{file_names[needed_by]} needs what it makes"
            elif works_on is not None:
                through[u] = f"it works on what {file_names[works_on]} makes"
            elif drives is not None:
                through[u] = f"it runs {file_names[drives]}"
            else:
                continue
            runs[u] = strong[u] = added = True
        if not added:
            return through


def _repro_sw_link_text(links: Sequence[str | None]) -> list[str | None]:
    """Port of R/reproducibility_check_software.R::.repro_sw_link_text().

    What links a file of software to the paper, in words, for ``table$paper_link``: the
    codes of stage 2 (``"paper_names_it, data"``) become sentences joined by ``"; "``, a
    link of step 7 is one already. ``None`` and ``""`` give ``None``.
    """
    out: list[str | None] = []
    for link in links:
        if is_missing(link) or not link:
            out.append(None)
            continue
        parts = [p for p in strsplit(str(link), ", ", fixed=True) if p is not None]
        out.append("; ".join(_LINK_WORDS.get(p, p) for p in parts))
    return out


def _repro_software_why(
    kind: Sequence[str | None], software: Sequence[str | None]
) -> list[str | None]:
    """Port of R/reproducibility_check_software.R::.repro_software_why().

    The sentence the report gives for each kind of file (see :func:`_repro_software_kind`);
    ``None`` for analysis (kind ``None``) and for a kind without a sentence. The name of
    the software is put in where the sentence has room for it.
    """
    out: list[str | None] = []
    for k, sw in zip(kind, software, strict=True):
        txt = None if is_missing(k) else _WHY_TEXT.get(str(k))
        out.append(None if txt is None else txt.replace("%s", "" if is_missing(sw) else f" {sw}"))
    return out


def _repro_not_analysis_why(why: Sequence[str | None]) -> list[str]:
    """Port of R/reproducibility_check_software.R::.repro_not_analysis_why().

    The sentence for a file that is not part of the analysis: *why* from
    :func:`_repro_software_kind`, or, when missing, the one for a package's tests and the
    ``setup.py`` that installs a package (:func:`_repro_is_r_test`,
    :func:`_repro_is_py_test`).
    """
    return [_TEST_WHY if is_missing(w) else str(w) for w in why]
