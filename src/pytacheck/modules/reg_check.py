"""RegCheck Preregistration Comparison (port of ``inst/modules/reg_check.R``).

The module takes the preregistrations found by ``prereg_check`` (from a
chained run, or by running ``prereg_check`` itself) and compares each one
with the full paper text through a RegCheck server
(:func:`pytacheck.db.regcheck.regcheck_compare`), one LLM judgement per
comparison dimension.
"""

from __future__ import annotations

from collections.abc import Sequence
from typing import Any

import pandas as pd

from pytacheck._r import as_character, bind_rows, gsub, is_na, plural, trimws
from pytacheck.module import module
from pytacheck.report import collapse_section, format_ref, scroll_table

__all__ = ["prereg_row_text", "reg_check"]

